"""Export real XGBoost and SHAP results on deterministic synthetic accounts."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_curve

from pipeline import FEATURE_COLUMNS, FraudConfig, FraudPipeline


def build() -> dict:
    """Generate noisy accounts, train on past filings, and export held-out scores."""
    rng = np.random.default_rng(21)
    rows, labels = [], []
    for cik in range(1, 49):
        revenue = float(rng.uniform(100, 300))
        for year in range(2013, 2024):
            pressure = float(rng.normal())
            fraud = int(rng.random() < 1 / (1 + np.exp(-(1.0 * pressure - 1.5))))
            revenue *= rng.uniform(0.92, 1.18)
            assets = revenue * rng.uniform(1.2, 1.8)
            rows.append(
                {
                    "cik": cik,
                    "fiscal_year": year,
                    "filing_date": f"{year + 1}-03-01",
                    "revenue": revenue,
                    "receivables": revenue
                    * np.clip(0.15 + pressure * 0.035 + rng.normal(0, 0.025), 0.02, 0.5),
                    "cogs": revenue * rng.uniform(0.45, 0.7),
                    "current_assets": assets * 0.3,
                    "ppe_net": assets * rng.uniform(0.3, 0.5),
                    "total_assets": assets,
                    "depreciation": assets * rng.uniform(0.02, 0.06),
                    "sga": revenue * 0.13,
                    "current_liabilities": assets * rng.uniform(0.1, 0.25),
                    "long_term_debt": assets * 0.2,
                    "income_continuing": revenue * 0.12,
                    "operating_cash_flow": revenue * (0.1 - pressure * 0.03 + rng.normal(0, 0.025)),
                }
            )
            if fraud:
                labels.append({"CIK": cik, "YEARA": year})
    pipeline = FraudPipeline(FraudConfig(2018, 2019, 2022))
    pipeline.load_data(pd.DataFrame(rows), pd.DataFrame(labels))
    pipeline.calculate_beneish_metrics()
    pipeline.train_xgboost()
    report = pipeline.evaluate_oot()
    audit = pipeline.run_shap_audit(print_top=False)
    assert (
        pipeline.oot_data is not None
        and pipeline.train_data is not None
        and pipeline.model is not None
    )
    test = pipeline.oot_data
    scores = pipeline.model.predict_proba(test[list(FEATURE_COLUMNS)])[:, 1]
    truth = test.fraud.to_numpy(dtype=int)
    fpr, tpr, _ = roc_curve(truth, scores)
    return {
        "kind": "sec",
        "synthetic": True,
        "seed": 21,
        "provenance": "Generated by build_demo.py using the repository XGBoost pipeline and TreeExplainer. Companies, statements, and enforcement labels are all synthetic. Labels are stochastic, not real SEC findings.",
        "training_note": "Training filings must precede January 2019. AAER-style labels are retrospective: this demo does not resolve real enforcement-availability delays.",
        "train_count": len(pipeline.train_data),
        "test_count": len(test),
        "source_count": len(rows),
        "purged_count": len(rows) - len(test) - len(pipeline.train_data),
        "truth": truth.tolist(),
        "records": [
            {
                "id": f"Synthetic Co. {int(row.cik):03d}",
                "year": int(row.fiscal_year),
                "target": int(row.fraud),
            }
            for row in test.itertuples()
        ],
        "models": {
            "xgboost": {
                "name": "Cost-sensitive XGBoost",
                "scores": scores.tolist(),
                "roc": np.column_stack([fpr, tpr]).tolist(),
                "roc_auc": report.roc_auc,
                "pr_auc": float(average_precision_score(truth, scores)),
                "decision_threshold": 0.5,
            }
        },
        "attribution": audit.to_dict(orient="records"),
        "cost_ratio": 10,
        "features": list(FEATURE_COLUMNS),
    }


if __name__ == "__main__":
    path = Path(__file__).parent / "docs" / "data.json"
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(build(), indent=2, allow_nan=False) + "\n")
    print(f"Exported synthetic demo to {path}")
